#!/usr/bin/env python3
"""Render the tracked schema and migrations for an empty PostgreSQL database."""
from pathlib import Path

from compare_schema_exports import _statement_blocks

ROOT = Path(__file__).resolve().parent


def render() -> str:
    statements = _statement_blocks((ROOT / "schema.sql").read_text())
    tables = [s for s in statements if s.startswith("CREATE TABLE ")]
    constraints = [s for s in statements if s.startswith("ALTER TABLE ")]
    indexes = [s for s in statements if s.startswith("CREATE INDEX ")]
    other = [s for s in statements if s not in tables + constraints + indexes]
    if other:
        raise ValueError(f"Unsupported schema statements: {other}")
    # Referenced primary/unique keys must exist before adding foreign keys.
    constraints.sort(key=lambda s: "FOREIGN KEY" in s)
    chunks = [
        "-- Generated by database/build_baseline.py; for an EMPTY database only.",
        "BEGIN;",
        "CREATE SCHEMA IF NOT EXISTS extensions;",
        "CREATE EXTENSION IF NOT EXISTS pg_trgm WITH SCHEMA extensions;",
        *tables,
        *constraints,
        *indexes,
    ]
    for migration in sorted((ROOT / "supabase/migrations").glob("*.sql")):
        sql = "\n".join(
            line
            for line in migration.read_text().splitlines()
            if not line.lstrip().upper().startswith(("GRANT ", "REVOKE "))
        )
        chunks.extend([f"-- Migration: {migration.name}", sql])
    chunks.append("COMMIT;")
    return "\n\n".join(chunks) + "\n"


if __name__ == "__main__":
    print(render(), end="")
