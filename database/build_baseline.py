#!/usr/bin/env python3
"""Render the tracked schema export and migrations as executable PostgreSQL SQL.

Supabase supplies auth.users and the API roles. Tests supply small local stubs.
Never run this empty-database baseline against an existing database.
"""
from pathlib import Path
import re

from compare_schema_exports import _statement_blocks

ROOT = Path(__file__).resolve().parent


def render() -> str:
    statements = _statement_blocks((ROOT / "schema.sql").read_text())
    tables = [s for s in statements if s.startswith("CREATE TABLE ")]
    constraints = [s for s in statements if s.startswith("ALTER TABLE ")]
    indexes = [s for s in statements if s.startswith("CREATE INDEX ")]
    other = [s for s in statements if s not in tables + constraints + indexes]
    if other:
        raise ValueError(f"Unsupported schema statements: {other}")
    # Referenced primary/unique keys must exist before adding foreign keys.
    constraints.sort(key=lambda s: "FOREIGN KEY" in s)
    chunks = [
        "-- Generated by database/build_baseline.py; for an EMPTY database only.",
        "BEGIN;",
        "CREATE SCHEMA IF NOT EXISTS extensions;",
        "CREATE EXTENSION IF NOT EXISTS pg_trgm WITH SCHEMA extensions;",
        *tables, *constraints, *indexes,
        "GRANT USAGE ON SCHEMA public, extensions TO service_role;",
    ]
    for statement in tables:
        table = re.match(r"CREATE TABLE (public\.\w+)", statement).group(1)
        chunks.extend([
            f"ALTER TABLE {table} ENABLE ROW LEVEL SECURITY;",
            f"REVOKE ALL ON TABLE {table} FROM PUBLIC, anon, authenticated;",
            f"GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE {table} TO service_role;",
            f"CREATE POLICY service_access ON {table} TO service_role USING (true) WITH CHECK (true);",
        ])
    for migration in sorted((ROOT / "supabase/migrations").glob("*.sql")):
        chunks.extend([f"-- Migration: {migration.name}", migration.read_text()])
    chunks.append("COMMIT;")
    return "\n\n".join(chunks) + "\n"


if __name__ == "__main__":
    print(render(), end="")
